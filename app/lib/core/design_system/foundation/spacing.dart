/// Standardized spacing foundation.
///
/// Ordinary screens should consume semantic spacing through [LayoutTokens]
/// via `context.layout.*` rather than hardcoding numbers.
abstract final class Spacing {
  /// 4.0
  static const xxs = 4.0;

  /// 8.0
  static const xs = 8.0;

  /// 12.0
  static const sm = 12.0;

  /// 16.0
  static const md = 16.0;

  /// 20.0
  static const lg = 20.0;

  /// 24.0
  static const xl = 24.0;

  /// 32.0
  static const xxl = 32.0;

  /// 40.0
  static const xxxl = 40.0;

  /// 48.0
  static const huge = 48.0;
}
